const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {existsSync}=require('node:fs');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({executablePath:process.env.RATED_TEST_CHROME||'/usr/bin/chromium',args:['--host-resolver-rules=MAP * ~NOTFOUND, EXCLUDE 127.0.0.1','--no-proxy-server']});
  const start=async(origin,width,real)=>{
    const page=await browser.newPage({viewport:{width,height:900}});
    page.setDefaultTimeout(6500);
    const errors=[],offsite=[],failed=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('response',r=>{if(r.status()>=400)failed.push(r.url());});
    await page.route('**/*',r=>{
      const url=new URL(r.request().url());
      if(url.origin!==origin){offsite.push(url.href);return r.abort();}
      if(real)return r.continue();
      const file=path.resolve(__dirname,'../dist',url.pathname.slice(1)||'index.html');
      return existsSync(file)?r.fulfill({path:file}):r.fulfill({status:404,body:''});
    });
    const open=hash=>page.goto(origin+'/'+hash);
    const button=name=>page.getByRole('button',{name,exact:true});
    const heading=name=>page.getByRole('heading',{name,exact:true});
    const field=name=>page.getByLabel(name,{exact:true});
    async function close(){
      assert.deepEqual(errors,[]);
      assert.deepEqual(offsite,[]);
      assert.deepEqual(failed.filter(url=>!url.endsWith('/favicon.ico')),[]);
      await page.context().close();
    }
    const noOverflow=async()=>assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    return {page,open,button,heading,field,close,noOverflow};
  };
  try{
    for(const width of [320,820,1366]){
      const {page,open,button,heading,field,close,noOverflow}=await start('http://127.0.0.1:8767',width,true);
      await open('#hq/finance');
      await heading('Posted revenue').waitFor();
      await button('Add Transaction').click();
      await field('Description').fill('Demo partnership payment');
      await field('Amount (USD)').fill('50.25');
      await field('Date').fill(new Date().toISOString().slice(0,8)+'09');
      await field('CRM contact').selectOption('contact-maya');
      await field('Frequency').selectOption('Monthly');
      await button('Save record').click();
      await heading('Demo partnership payment').waitFor();
      await button('Edit Demo partnership payment').click();
      await field('Amount (USD)').fill('65.25');
      await button('Save record').click();
      await page.reload();
      const financeCard=page.locator('article').filter({has:heading('Demo partnership payment')});
      await financeCard.getByText(/\$65\.25/).waitFor();
      await financeCard.getByText(/Maya Vale/).waitFor();
      await field('Report period').selectOption('Year');
      await heading('Projected net').waitFor();
      await button('Projected income').click();
      await page.getByText('Projected recurrence',{exact:true}).first().waitFor();
      await button('Delete Demo partnership payment').click();
      await button('Delete record').click();
      await heading('Demo partnership payment').first().waitFor({state:'detached'});
      await noOverflow();

      await open('#hq/territory');
      await button('6 · Hudson Valley').click();
      await heading('Hudson Lantern Farm').waitFor();
      assert.equal(await heading('North Loop Dispensary').count(),0);
      await page.getByText('Business profile',{exact:true}).last().click();
      await page.getByText(/CRM · Hudson Lantern Farm/).waitFor();
      await button('Add Business').click();
      await field('Business name').fill('Offline Terrain Test');
      await field('Region').selectOption('hudson');
      await field('Category').selectOption('Processor');
      await button('Save record').click();
      await heading('Offline Terrain Test').waitFor();
      await button('Edit Offline Terrain Test').click();
      await field('Product intelligence').fill('Demo resin');
      await button('Save record').click();
      await page.reload();
      await field('Search records').fill('Demo resin');
      await heading('Offline Terrain Test').waitFor();
      await button('Delete Offline Terrain Test').click();
      await button('Delete record').click();
      await page.getByText('0 records',{exact:false}).waitFor();
      await noOverflow();

      await open('#community/stash');
      await button('Add Journal entry').click();
      await field('Product').fill('Test Citrus');
      await field('Brand').fill('Demo brand');
      await field('Private tasting notes').fill('PRIVATE-ONLY-0123');
      for(const label of ['Aesthetic','Aroma','Flavor','Effects','Overall'])await field(label).fill('70');
      await button('Save record').click();
      await heading('Test Citrus').waitFor();
      await button('Edit Test Citrus').click();
      await field('Flavor').fill('75');
      await button('Save record').click();
      await page.reload();
      const journal=page.locator('article').filter({has:heading('Test Citrus')});
      await journal.getByText(/355 \/ 420/).waitFor();
      await journal.getByRole('button',{name:'Preview public review'}).click();
      await button('Confirm publication').click();
      await page.getByRole('dialog').waitFor();
      await button('Cancel').click();
      await open('#community/reviews');
      await page.getByText('No published demo reviews.').waitFor();
      await open('#community/stash');
      await journal.getByRole('button',{name:'Preview public review'}).click();
      assert.equal(await field('Public review text').inputValue(),'');
      await field('Public review text').fill('Public synthetic review');
      await field('I confirm this review may appear in the public demo').check();
      await button('Confirm publication').click();
      await page.getByText('Review published to the community review preview.').waitFor();
      await open('#community/reviews');
      await page.getByText('Public synthetic review').waitFor();
      assert(!((await page.locator('body').innerText()).includes('PRIVATE-ONLY-0123')));
      assert.equal(await page.locator('#expansion-view article').count(),1);
      await open('#community/stash');
      await button('Delete Test Citrus').click();
      await button('Delete record').click();
      await heading('Test Citrus').waitFor({state:'detached'});
      await button('Reset The Stash').click();
      await button('Reset records').click();
      await heading('Demo Citrus').waitFor();
      await noOverflow();await close();
      console.log('Expansion CRUD, projection, territory, consent and privacy passed at '+width+'px');
    }
    const {page,open,button,heading,field,close}=await start('http://127.0.0.1:8815',820,false);
    await open('#hq/gary/finance');
    await page.locator('#ageYes').click();
    const denied=()=>page.getByText('Rated420 HQ is available to authorized staff.').waitFor();
    await denied();
    await page.locator('#demoReviewer').selectOption({label:'Reviewer A'});
    await page.locator('#accountPage').waitFor();
    await button('Open The Stash').click();
    await heading('The Stash').waitFor();
    await button('Edit Demo Citrus').click();
    await field('Private tasting notes').fill('Account A only');
    await button('Save record').click();
    await page.getByText('Account A only').waitFor();
    await page.locator('#demoReviewer').selectOption({label:'Reviewer B'});
    await button('Open The Stash').click();
    await page.locator('#accountStash').getByRole('heading',{name:'Demo Citrus',exact:true}).waitFor();
    assert.equal(await page.getByText('Account A only').count(),0);
    await open('#hq/gary/territory');
    await denied();
    await page.locator('#demoReviewer').selectOption({label:'Staff member'});
    await open('#hq/gary/territory');
    await heading('Territory Explorer').waitFor();
    await close();
    console.log('Integrated staff access and per-account Stash isolation passed.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
